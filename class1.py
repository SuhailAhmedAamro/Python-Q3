# ## **1. Introduction to Python**  

# ### **What is Python?**  
# Python is a **high-level, interpreted programming language** that is widely used for:  
# ✅ Web development (Django, Flask)  
# ✅ Data science and machine learning (NumPy, Pandas, TensorFlow)  
# ✅ Automation and scripting  
# ✅ Cybersecurity and ethical hacking  
# ✅ Desktop and mobile applications  

# ---

# ### **Features and Benefits of Python**  
# ✔ **Easy to Read and Write:** Python has a simple and clean syntax like English.  
# ✔ **Cross-Platform:** Runs on Windows, macOS, Linux.  
# ✔ **Interpreted Language:** No need for compilation; Python executes code line by line.  
# ✔ **Large Community & Libraries:** Thousands of built-in and third-party libraries.  
# ✔ **Open Source:** Free to use and modify.  
# ✔ **Dynamically Typed:** No need to declare variable types (e.g., `x = 10` works without specifying `int`).  

# ---

# ### **Installing Python**  

# #### **Method 1: Install from Python.org (Standard Python)**
# 1️⃣ Visit **[python.org/downloads](https://www.python.org/downloads/)**  
# 2️⃣ Download the latest Python version for your OS.  
# 3️⃣ Run the installer and check **“Add Python to PATH”** before installing.  
# 4️⃣ Open the terminal (Command Prompt, Terminal, or PowerShell).  
#    ```bash
#    python --version
#    ```
#    If it prints `Python 3.x.x`, Python is installed correctly.

# ---

# #### **Method 2: Install Anaconda (Recommended for Data Science)**
# 1️⃣ Download Anaconda from **[anaconda.com](https://www.anaconda.com/)**  
# 2️⃣ Install it and open the **Anaconda Navigator** or **Anaconda Prompt**  
# 3️⃣ To check installation:
#    ```bash
#    conda --version
#    ```

