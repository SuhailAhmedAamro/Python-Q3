# ### **Running Python Code in Different Ways**  

# #### ✅ **1. Python Console (Interactive Mode)**
# - Open **Command Prompt** (Windows) or **Terminal** (Mac/Linux)  
# - Type `python` or `python3` and press Enter  
# - Write:
#   ```python
#   print("Hello, World!")
#   ```
# - Press **Enter**, and it will print:
#   ```
#   Hello, World!
#   ```

# ---

# #### ✅ **2. Python Script (`.py` file)**
# 1️⃣ Open a text editor (VS Code, Notepad++, PyCharm).  
# 2️⃣ Create a new file named `hello.py`.  
# 3️⃣ Write:
#    ```python
#    print("Hello, World!")
#    ```
# 4️⃣ Save the file and run it in the terminal:
#    ```bash
#    python hello.py
#    ```
# 5️⃣ Output:  
#    ```
